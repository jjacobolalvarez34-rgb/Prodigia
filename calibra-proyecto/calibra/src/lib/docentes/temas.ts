export function nombreTema(tema: string, locale: string): string {
  const n = NOMBRE_TEMA[tema];
  if (n) return locale.startsWith("en") ? n[1] : n[0];
  const limpio = tema.replace(/^[a-z]+_/, "").replace(/[_-]+/g, " ");
  return limpio.charAt(0).toUpperCase() + limpio.slice(1);
}
