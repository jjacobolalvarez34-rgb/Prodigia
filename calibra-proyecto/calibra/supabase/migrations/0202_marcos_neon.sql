-- en 3 colores distintos. Reinterpretado en CSS puro (ver el comentario
-- largo en src/types/database.ts y el bloque .marco-neon-* en
-- src/app/globals.css) en vez de incrustar el video: 3 marcos nuevos,
-- misma mecánica que los 6 marcos de rango (bronce..prodigio) — solo
-- Chispas, sin requisito de nivel_mundo, mismo precio los 3 (variantes
